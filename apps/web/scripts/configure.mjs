#!/usr/bin/env node
// =============================================================================
// Photovoks setup wizard:  pnpm configure
//
// Asks a few questions, checks the connection, and writes apps/web/.env.local.
// Re-running keeps your previous answers as defaults (just press Enter).
//
//   pnpm configure          full setup
//   pnpm configure --pin    only change the admin PIN
// =============================================================================

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import readline from 'node:readline';
import { fileURLToPath } from 'node:url';
import bcrypt from 'bcryptjs';
import { createClient } from '@supabase/supabase-js';
import { listPrinters } from '../print-worker/worker.mjs';

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envFile = path.join(webDir, '.env.local');

// ── tiny helpers ─────────────────────────────────────────────────────────────

const c = {
  bold: (s) => `\x1b[1m${s}\x1b[0m`,
  green: (s) => `\x1b[32m${s}\x1b[0m`,
  red: (s) => `\x1b[31m${s}\x1b[0m`,
  dim: (s) => `\x1b[2m${s}\x1b[0m`,
  pink: (s) => `\x1b[35m${s}\x1b[0m`,
};

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
let muted = false;
// Silent input for PINs (like `sudo`): typed characters are not echoed.
const writeOut = rl._writeToOutput.bind(rl);
rl._writeToOutput = (s) => {
  if (!muted) writeOut(s);
  else if (s.includes('\n')) writeOut('\n');
};

function ask(question, def = '') {
  const hint = def ? c.dim(` [${def.length > 24 ? def.slice(0, 10) + '…' + def.slice(-6) : def}]`) : '';
  return new Promise((resolve) => rl.question(`${question}${hint}: `, (a) => resolve(a.trim() || def)));
}

async function askSecret(question) {
  const promise = new Promise((resolve) => rl.question(`${question} ${'\x1b[2m'}(tidak tampil saat diketik)${'\x1b[0m'}: `, (a) => resolve(a.trim())));
  muted = true; // prompt is already written; hide what is typed next
  const answer = await promise;
  muted = false;
  return answer;
}

function readEnv() {
  if (!fs.existsSync(envFile)) return {};
  const out = {};
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return out;
}

function writeEnv(values) {
  const lines = [
    '# Photovoks — generated by `pnpm configure`. KEEP THIS FILE PRIVATE (never commit it).',
    '',
    '# Supabase (Project Settings → API)',
    `NEXT_PUBLIC_SUPABASE_URL=${values.NEXT_PUBLIC_SUPABASE_URL}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${values.NEXT_PUBLIC_SUPABASE_ANON_KEY}`,
    `SUPABASE_SERVICE_ROLE_KEY=${values.SUPABASE_SERVICE_ROLE_KEY}`,
    '',
    '# Google Gemini (https://aistudio.google.com/apikey) — leave empty to disable AI doodles',
    `GEMINI_API_KEY=${values.GEMINI_API_KEY ?? ''}`,
    `GEMINI_MODEL_NAME=${values.GEMINI_MODEL_NAME || 'gemini-2.5-flash-image'}`,
    '',
    '# Printer name (`pnpm print --list`). "dry-run" = save files to ./print-output. Empty = no printing here.',
    `PRINTER_NAME=${values.PRINTER_NAME ?? ''}`,
    '',
    '# Signs admin sessions. Auto-generated; changing it logs out every admin.',
    `ADMIN_SESSION_SECRET=${values.ADMIN_SESSION_SECRET}`,
    '',
  ];
  fs.writeFileSync(envFile, lines.join('\n'), { mode: 0o600 });
}

function fail(msg) {
  console.error(`\n${c.red('✖')} ${msg}\n`);
  rl.close();
  process.exit(1);
}

// ── steps ────────────────────────────────────────────────────────────────────

async function setPin(supabase) {
  let pin = '';
  for (;;) {
    pin = await askSecret('PIN admin baru (4–8 angka, disarankan 6)');
    if (!/^\d{4,8}$/.test(pin)) {
      console.log(c.red('  PIN harus 4–8 digit angka.'));
      continue;
    }
    if (/^(\d)\1+$/.test(pin) || '0123456789'.includes(pin) || '9876543210'.includes(pin)) {
      console.log(c.red('  PIN terlalu mudah ditebak (mis. 1111 / 1234). Pilih yang lain.'));
      continue;
    }
    const again = await askSecret('Ulangi PIN');
    if (again !== pin) {
      console.log(c.red('  PIN tidak sama, coba lagi.'));
      continue;
    }
    break;
  }
  const hash = await bcrypt.hash(pin, 12);
  const { error } = await supabase
    .from('admin_users')
    .upsert({ username: 'admin', pin_hash: hash, failed_attempts: 0, locked_until: null }, { onConflict: 'username' });
  if (error) fail(`Gagal menyimpan PIN: ${error.message}`);
  console.log(c.green('  ✔ PIN admin disimpan (hanya hash-nya yang disimpan).'));
}

async function main() {
  const prev = readEnv();
  const onlyPin = process.argv.includes('--pin');

  console.log(`\n${c.pink(c.bold('📸 Photovoks setup'))}\n`);

  if (onlyPin) {
    if (!prev.SUPABASE_SERVICE_ROLE_KEY) fail('Belum ada .env.local. Jalankan `pnpm configure` dulu.');
    const supabase = createClient(prev.NEXT_PUBLIC_SUPABASE_URL, prev.SUPABASE_SERVICE_ROLE_KEY, {
      auth: { persistSession: false },
    });
    await setPin(supabase);
    rl.close();
    return;
  }

  // 1. Supabase
  console.log(c.bold('1) Supabase') + c.dim('  — Dashboard → Project Settings → API'));
  const url = await ask('   Project URL (https://xxxx.supabase.co)', prev.NEXT_PUBLIC_SUPABASE_URL);
  if (!/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)\/?$/.test(url) && !/^https?:\/\/(localhost|127\.0\.0\.1)(:\d+)?\/?$/.test(url)) {
    fail('URL Supabase tidak valid.');
  }
  const anon = await ask('   anon / publishable key', prev.NEXT_PUBLIC_SUPABASE_ANON_KEY);
  const service = await ask('   service_role / secret key (RAHASIA)', prev.SUPABASE_SERVICE_ROLE_KEY);
  if (!anon || !service) fail('Kedua key Supabase wajib diisi.');
  if (anon === service) fail('anon key dan service_role key tidak boleh sama.');

  const supabase = createClient(url.replace(/\/$/, ''), service, { auth: { persistSession: false } });
  process.stdout.write('   Mengecek koneksi & database… ');
  const { error: dbError } = await supabase.from('admin_users').select('id').limit(1);
  if (dbError) {
    console.log(c.red('gagal'));
    if (/does not exist|schema cache/i.test(dbError.message)) {
      fail(
        'Tabel database belum ada. Jalankan migrasi dulu (lihat README, langkah "Siapkan database"),\n  lalu ulangi `pnpm configure`.',
      );
    }
    fail(`Tidak bisa terhubung ke Supabase: ${dbError.message}`);
  }
  console.log(c.green('ok'));

  // 2. Gemini
  console.log(`\n${c.bold('2) Gemini AI')}${c.dim('  — https://aistudio.google.com/apikey (kosongkan untuk mematikan doodle AI)')}`);
  const gemini = await ask('   Gemini API key', prev.GEMINI_API_KEY);

  // 3. Printer
  console.log(`\n${c.bold('3) Printer')}${c.dim('  — isi di komputer yang tersambung ke printer')}`);
  const printers = await listPrinters();
  printers.forEach((p, i) => console.log(`   ${i + 1}. ${p}`));
  console.log(`   d. dry-run ${c.dim('(tidak mencetak, simpan file ke folder print-output — untuk tes)')}`);
  console.log(`   0. tidak ada printer di komputer ini`);
  const defChoice = prev.PRINTER_NAME
    ? prev.PRINTER_NAME === 'dry-run'
      ? 'd'
      : String(printers.indexOf(prev.PRINTER_NAME) + 1 || prev.PRINTER_NAME)
    : printers.length
      ? '1'
      : 'd';
  const choice = await ask('   Pilih', defChoice);
  let printer = '';
  if (choice === 'd') printer = 'dry-run';
  else if (choice === '0') printer = '';
  else if (/^\d+$/.test(choice) && printers[Number(choice) - 1]) printer = printers[Number(choice) - 1];
  else printer = choice; // typed a printer name manually

  // 4. Admin PIN
  console.log(`\n${c.bold('4) PIN admin')}${c.dim('  — untuk masuk ke /admin (tap 5x pojok kanan atas di layar booth)')}`);
  const { data: admin } = await supabase.from('admin_users').select('id').eq('username', 'admin').maybeSingle();
  if (!admin || (await ask('   Ganti PIN admin? (y/N)', 'N')).toLowerCase() === 'y') {
    await setPin(supabase);
  }

  // 5. Event
  const { data: activeEvent } = await supabase.from('events').select('id, name').eq('status', 'active').maybeSingle();
  if (!activeEvent) {
    console.log(`\n${c.bold('5) Event')}`);
    const name = await ask('   Belum ada event aktif. Nama event pertama', 'Photovoks Event');
    const { error } = await supabase.from('events').insert({ name, status: 'active' });
    if (error) fail(`Gagal membuat event: ${error.message}`);
    console.log(c.green(`   ✔ Event "${name}" dibuat & diaktifkan. Upload bingkai di /admin/frames.`));
  } else {
    console.log(`\n${c.bold('5) Event')}  aktif: ${c.green(activeEvent.name)}`);
  }

  writeEnv({
    NEXT_PUBLIC_SUPABASE_URL: url.replace(/\/$/, ''),
    NEXT_PUBLIC_SUPABASE_ANON_KEY: anon,
    SUPABASE_SERVICE_ROLE_KEY: service,
    GEMINI_API_KEY: gemini,
    GEMINI_MODEL_NAME: prev.GEMINI_MODEL_NAME,
    PRINTER_NAME: printer,
    ADMIN_SESSION_SECRET: prev.ADMIN_SESSION_SECRET || crypto.randomBytes(48).toString('base64url'),
  });

  console.log(`\n${c.green('✔ Selesai!')} Konfigurasi disimpan di ${c.dim(path.relative(process.cwd(), envFile) || envFile)}\n`);
  console.log(`  Jalankan booth:   ${c.bold('pnpm booth')}`);
  console.log(`  Admin panel:      ${c.bold('http://localhost:3000/admin')}\n`);
  rl.close();
}

main().catch((err) => fail(err?.message || String(err)));
